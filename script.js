function renderCartPage() {
  const container = document.getElementById("cart-items-container");
  const summary = document.getElementById("cart-summary");
  if (!container) return;

  const cart = getCart();

  if (!cart.length) {
    container.innerHTML = '<div class="empty-state">Your cart is empty. Add a few items to continue shopping.</div>';
    if (summary) summary.innerHTML = '<div class="summary-card"><h3>Order summary</h3><p>Nothing in cart yet.</p></div>';
    return;
  }

  const items = cart.map((entry) => {
    const product = productsData.find((item) => item.id === entry.id);
    return {
      ...entry,
      product,
    };
  }).filter((entry) => entry.product);

  const subtotal = items.reduce((sum, item) => sum + item.product.price * item.qty, 0);
  container.innerHTML = items.map((entry) => `
    <article class="cart-item">
      <img src="${entry.product.image}" alt="${entry.product.name}" />
      <div class="cart-meta">
        <h3>${entry.product.name}</h3>
        <p>${entry.product.shortDescription}</p>
        <div class="cart-actions">
          <div class="qty-controls">
            <button data-action="decrease" data-product-id="${entry.id}">−</button>
            <span>${entry.qty}</span>
            <button data-action="increase" data-product-id="${entry.id}">+</button>
          </div>
          <button class="secondary-btn" data-action="remove" data-product-id="${entry.id}">Remove</button>
        </div>
      </div>
      <div class="item-price">${formatCurrency(entry.product.price * entry.qty)}</div>
    </article>
  `).join("");

  if (summary) {
    summary.innerHTML = `
      <div class="summary-card">
        <h3>Order summary</h3>
        <div class="summary-row"><span>Subtotal</span><span>${formatCurrency(subtotal)}</span></div>
        <div class="summary-row"><span>Delivery</span><span>By location</span></div>
        <div class="summary-row total"><span>Items subtotal</span><span>${formatCurrency(subtotal)}</span></div>
        <p class="delivery-note">Delivery fees are confirmed for your address at checkout.</p>
        <a href="checkout.html" class="primary-btn" style="display:inline-flex; margin-top:18px; width:100%; justify-content:center;">Proceed to checkout</a>
      </div>
    `;
  }

  document.querySelectorAll("[data-action]").forEach((button) => {
    const productId = Number(button.dataset.productId);
    const action = button.dataset.action;

    button.addEventListener("click", () => {
      const cartList = getCart();
      const item = cartList.find((entry) => entry.id === productId);

      if (!item) return;

      if (action === "increase") item.qty += 1;
      if (action === "decrease") item.qty = Math.max(1, item.qty - 1);
      if (action === "remove") {
        const index = cartList.findIndex((entry) => entry.id === productId);
        cartList.splice(index, 1);
      }

      saveCart(cartList);
      renderCartPage();
      updateCartBadge();
    });
  });
}

function validateCheckoutForm() {
  const form = document.getElementById("checkout-form");
  if (!form) return false;

  const requiredFields = [
    { id: "first-name", message: "Please enter your first name." },
    { id: "last-name", message: "Please enter your last name." },
    { id: "email", message: "Please enter a valid email address." },
    { id: "phone", message: "Please enter a Nigerian phone number." },
    { id: "address", message: "Please enter your delivery address." },
    { id: "city", message: "Please select your city." },
    { id: "state", message: "Please select your state." },
    { id: "payment-method", message: "Please select a payment method." }
  ];

  let valid = true;

  requiredFields.forEach(({ id, message }) => {
    const field = document.getElementById(id)?.closest(".field");
    const input = document.getElementById(id);

    if (!input || !input.value.trim()) {
      field?.classList.add("error");
      const small = field?.querySelector("small");
      if (small) small.textContent = message;
      valid = false;
      return;
    }

    if (id === "email" && !/\S+@\S+\.\S+/.test(input.value)) {
      field?.classList.add("error");
      const small = field?.querySelector("small");
      if (small) small.textContent = "Please use a valid email address.";
      valid = false;
      return;
    }

    if (id === "phone" && !/^\+?\d{10,15}$/.test(input.value.replace(/\s+/g, ""))) {
      field?.classList.add("error");
      const small = field?.querySelector("small");
      if (small) small.textContent = "Please enter a valid Nigerian phone number.";
      valid = false;
      return;
    }

    field?.classList.remove("error");
  });

  return valid;
}

