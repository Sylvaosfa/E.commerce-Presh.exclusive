const cartStorageKey = "presh_exclusive_cart_v2";
const catalogPageSize = 12;
let catalogCurrentPage = 1;

function formatCurrency(value) {
  return new Intl.NumberFormat("en-NG", {
    style: "currency",
    currency: "NGN",
    maximumFractionDigits: 0,
  }).format(value);
}

function getCart() {
  const raw = localStorage.getItem(cartStorageKey);
  return raw ? JSON.parse(raw) : [];
}

function saveCart(cart) {
  localStorage.setItem(cartStorageKey, JSON.stringify(cart));
}

function updateCartBadge() {
  const countEl = document.getElementById("cart-count");
  if (!countEl) return;

  const cart = getCart();
  const totalItems = cart.reduce((sum, item) => sum + item.qty, 0);
  countEl.textContent = totalItems;
}

function addToCart(productId) {
  const product = productsData.find((item) => item.id === productId);
  if (!product || product.stock === "Out of stock") return;

  const cart = getCart();
  const item = cart.find((entry) => entry.id === productId);

  if (item) {
    item.qty += 1;
  } else {
    cart.push({ id: productId, qty: 1 });
  }

  saveCart(cart);
  updateCartBadge();
}

function renderProductCard(product, variant = "product") {
  const unavailable = product.stock === "Out of stock";

  return `
    <article class="${variant === "deal" ? "deal-card" : "product-card"}">
      <div class="card-top">
        <a href="product.html?id=${product.id}"><img src="${product.image}" alt="${product.name}" /></a>
      </div>
      <div class="${variant === "deal" ? "deal-body" : "product-body"}">
        <span class="category-label">${product.category}</span>
        <a href="product.html?id=${product.id}"><h3>${product.name}</h3></a>
        <div class="price-row">
          <strong>${formatCurrency(product.price)}</strong>
        </div>
        <button class="add-cart" data-product-id="${product.id}" ${unavailable ? "disabled" : ""}>${unavailable ? "Out of stock" : "Add to Cart"}</button>
      </div>
    </article>
  `;
}

function renderHomeProducts() {
  if (document.body.classList.contains("storefront-home")) return;

  const dealContainer = document.getElementById("flash-deals");
  const productContainer = document.getElementById("home-product-grid");

  if (dealContainer) {
    dealContainer.innerHTML = productsData.slice(0, 4).map((product) => renderProductCard(product, "deal")).join("");
  }

  if (productContainer) {
    productContainer.innerHTML = productsData.slice(4).map((product) => renderProductCard(product)).join("");
  }

  document.querySelectorAll(".add-cart").forEach((button) => {
    button.addEventListener("click", () => {
      addToCart(Number(button.dataset.productId));
      button.textContent = "Added";
      button.disabled = true;
      setTimeout(() => {
        button.textContent = "Add to cart";
        button.disabled = false;
      }, 1000);
    });
  });
}

function renderCatalog() {
  const catalogGrid = document.getElementById("catalog-grid");
  const searchInput = document.getElementById("catalog-search") || document.getElementById("catalog-search-main");
  const mainSearchInput = document.getElementById("catalog-search-main");
  const sortSelect = document.getElementById("catalog-sort");
  const categorySelect = document.getElementById("catalog-category");
  const resultCount = document.getElementById("result-count");
  const pagination = document.getElementById("catalog-pagination");

  if (!catalogGrid) return;

  const search = (searchInput?.value || mainSearchInput?.value || "").toLowerCase();
  const category = categorySelect?.value || document.querySelector(".pill.active")?.dataset.category || "all";
  const sort = sortSelect?.value || "featured";

  let filtered = productsData.filter((product) => {
    const matchesCategory = category === "all" || product.category === category;
    const matchesSearch = product.name.toLowerCase().includes(search) || product.shortDescription.toLowerCase().includes(search);
    return matchesCategory && matchesSearch;
  });

  if (sort === "price-low") filtered.sort((a, b) => a.price - b.price);
  if (sort === "price-high") filtered.sort((a, b) => b.price - a.price);
  if (sort === "rating") filtered.sort((a, b) => b.rating - a.rating);
  if (sort === "name") filtered.sort((a, b) => a.name.localeCompare(b.name));

  if (resultCount) resultCount.textContent = `${filtered.length} products`;

  if (!filtered.length) {
    catalogGrid.innerHTML = '<div class="empty-state">No products match your filters. Try another search or category.</div>';
    if (pagination) pagination.innerHTML = "";
    return;
  }

  const pageCount = Math.ceil(filtered.length / catalogPageSize);
  catalogCurrentPage = Math.min(catalogCurrentPage, pageCount);
  const firstItem = (catalogCurrentPage - 1) * catalogPageSize;
  const pageProducts = filtered.slice(firstItem, firstItem + catalogPageSize);
  catalogGrid.innerHTML = pageProducts.map((product) => renderProductCard(product)).join("");

  catalogGrid.querySelectorAll(".add-cart:not(:disabled)").forEach((button) => {
    button.addEventListener("click", () => {
      addToCart(Number(button.dataset.productId));
      button.textContent = "Added";
      button.disabled = true;
      setTimeout(() => {
        button.textContent = "Add to cart";
        button.disabled = false;
      }, 1000);
    });
  });

  if (pagination) {
    pagination.innerHTML = pageCount > 1 ? `
      <button class="page-button" type="button" data-page="${catalogCurrentPage - 1}" ${catalogCurrentPage === 1 ? "disabled" : ""} aria-label="Previous page">‹</button>
      ${Array.from({ length: pageCount }, (_, index) => index + 1).map((page) => `
        <button class="page-button ${page === catalogCurrentPage ? "active" : ""}" type="button" data-page="${page}" aria-label="Page ${page}" aria-current="${page === catalogCurrentPage ? "page" : "false"}">${page}</button>
      `).join("")}
      <button class="page-button" type="button" data-page="${catalogCurrentPage + 1}" ${catalogCurrentPage === pageCount ? "disabled" : ""} aria-label="Next page">›</button>
    ` : "";

    pagination.querySelectorAll("[data-page]").forEach((button) => {
      button.addEventListener("click", () => {
        catalogCurrentPage = Number(button.dataset.page);
        renderCatalog();
        catalogGrid.scrollIntoView({ behavior: "smooth", block: "start" });
      });
    });
  }
}

