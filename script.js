function setupNewsletter() {
  const form = document.querySelector(".newsletter-form");
  if (!form) return;

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    const input = form.querySelector("input");
    if (!input.value.trim()) {
      input.focus();
      return;
    }

    const button = form.querySelector("button");
    button.textContent = "Subscribed";
    button.disabled = true;
    input.value = "";
  });
}

function setupSearch() {
  const forms = document.querySelectorAll(".search-box");
  forms.forEach((form) => {
    form.addEventListener("submit", (event) => {
      const value = form.querySelector("input").value.trim();
      if (!value) {
        event.preventDefault();
      }
    });
  });
}

function setupCatalogUI() {
  const searchInput = document.getElementById("catalog-search");
  const mainSearchInput = document.getElementById("catalog-search-main");
  const categorySelect = document.getElementById("catalog-category");
  const sortSelect = document.getElementById("catalog-sort");
  const params = new URLSearchParams(window.location.search);

  if (params.get("category") && categorySelect) {
    categorySelect.value = params.get("category");
  }
  if (params.get("search")) {
    [searchInput, mainSearchInput].forEach((input) => {
      if (input) input.value = params.get("search");
    });
  }
  if (params.get("category")) {
    document.querySelectorAll(".pill").forEach((pill) => {
      pill.classList.toggle("active", pill.dataset.category === params.get("category"));
    });
  }

  [searchInput, mainSearchInput, categorySelect, sortSelect].forEach((control) => {
    if (!control) return;
    control.addEventListener("input", () => {
      if (control === searchInput && mainSearchInput) mainSearchInput.value = searchInput.value;
      if (control === mainSearchInput && searchInput) searchInput.value = mainSearchInput.value;
      catalogCurrentPage = 1;
      renderCatalog();
    });
    control.addEventListener("change", () => {
      if (control === searchInput && mainSearchInput) mainSearchInput.value = searchInput.value;
      if (control === mainSearchInput && searchInput) searchInput.value = mainSearchInput.value;
      catalogCurrentPage = 1;
      renderCatalog();
    });
  });

  document.querySelectorAll(".pill").forEach((pill) => {
    pill.addEventListener("click", () => {
      document.querySelectorAll(".pill").forEach((item) => item.classList.remove("active"));
      pill.classList.add("active");
      if (categorySelect) categorySelect.value = pill.dataset.category || "all";
      catalogCurrentPage = 1;
      renderCatalog();
    });
  });
}

